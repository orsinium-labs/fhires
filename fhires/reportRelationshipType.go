package fhires

// The type of relationship between reports.
//
// Status: draft
//
// http://hl7.org/fhir/ValueSet/report-relation-type
type ReportRelationshipType string

const (
	// This document replaces or supersedes the target document.
	ReportRelationshipTypeReplaces ReportRelationshipType = "replaces"
	// This document notes corrections or changes to replace or supersede parts of the target document.
	ReportRelationshipTypeAmends ReportRelationshipType = "amends"
	// This document adds additional information to the target document.
	ReportRelationshipTypeAppends ReportRelationshipType = "appends"
	// This document was generated by transforming the target document (eg format or language conversion).
	ReportRelationshipTypeTransforms ReportRelationshipType = "transforms"
	// This document was.
	ReportRelationshipTypeReplacedWith ReportRelationshipType = "replacedWith"
	// This document was.
	ReportRelationshipTypeAmendedWith ReportRelationshipType = "amendedWith"
	// This document was.
	ReportRelationshipTypeAppendedWith ReportRelationshipType = "appendedWith"
	// This document was.
	ReportRelationshipTypeTransformedWith ReportRelationshipType = "transformedWith"
)

func (code ReportRelationshipType) String() string {
	return code.Code()
}

func (code ReportRelationshipType) Code() string {
	return string(code)
}

func (code ReportRelationshipType) Display() string {
	switch code {
	case ReportRelationshipTypeReplaces:
		return "Replaces"
	case ReportRelationshipTypeAmends:
		return "Amends"
	case ReportRelationshipTypeAppends:
		return "Appends"
	case ReportRelationshipTypeTransforms:
		return "Transforms"
	case ReportRelationshipTypeReplacedWith:
		return "Replaced With"
	case ReportRelationshipTypeAmendedWith:
		return "Amended With"
	case ReportRelationshipTypeAppendedWith:
		return "Appended With"
	case ReportRelationshipTypeTransformedWith:
		return "Transformed With"
	}
	return "<unknown>"
}

func (code ReportRelationshipType) Definition() string {
	switch code {
	case ReportRelationshipTypeReplaces:
		return "This document replaces or supersedes the target document."
	case ReportRelationshipTypeAmends:
		return "This document notes corrections or changes to replace or supersede parts of the target document."
	case ReportRelationshipTypeAppends:
		return "This document adds additional information to the target document."
	case ReportRelationshipTypeTransforms:
		return "This document was generated by transforming the target document (eg format or language conversion)."
	case ReportRelationshipTypeReplacedWith:
		return "This document was."
	case ReportRelationshipTypeAmendedWith:
		return "This document was."
	case ReportRelationshipTypeAppendedWith:
		return "This document was."
	case ReportRelationshipTypeTransformedWith:
		return "This document was."
	}
	return "<unknown>"
}
