package fhires

// A code that indicates how the page is generated.
//
// Status: draft
//
// http://hl7.org/fhir/ValueSet/guide-page-generation
type GuidePageGeneration string

const (
	// Page is proper xhtml with no templating.  Will be brought across unchanged for standard post-processing.
	GuidePageGenerationHtml GuidePageGeneration = "html"
	// Page is markdown with templating.  Will use the template to create a file that imports the markdown file prior to post-processing.
	GuidePageGenerationMarkdown GuidePageGeneration = "markdown"
	// Page is xml with templating.  Will use the template to create a file that imports the source file and run the nominated XSLT transform (see parameters) if present prior to post-processing.
	GuidePageGenerationXml GuidePageGeneration = "xml"
	// Page will be generated by the publication process - no source to bring across.
	GuidePageGenerationGenerated GuidePageGeneration = "generated"
)

func (code GuidePageGeneration) String() string {
	return code.Code()
}

func (code GuidePageGeneration) Code() string {
	return string(code)
}

func (code GuidePageGeneration) Display() string {
	switch code {
	case GuidePageGenerationHtml:
		return "HTML"
	case GuidePageGenerationMarkdown:
		return "Markdown"
	case GuidePageGenerationXml:
		return "XML"
	case GuidePageGenerationGenerated:
		return "Generated"
	}
	return "<unknown>"
}

func (code GuidePageGeneration) Definition() string {
	switch code {
	case GuidePageGenerationHtml:
		return "Page is proper xhtml with no templating.  Will be brought across unchanged for standard post-processing."
	case GuidePageGenerationMarkdown:
		return "Page is markdown with templating.  Will use the template to create a file that imports the markdown file prior to post-processing."
	case GuidePageGenerationXml:
		return "Page is xml with templating.  Will use the template to create a file that imports the source file and run the nominated XSLT transform (see parameters) if present prior to post-processing."
	case GuidePageGenerationGenerated:
		return "Page will be generated by the publication process - no source to bring across."
	}
	return "<unknown>"
}
